#!/usr/bin/env python3
"""Merlin private-window artwork, retaining all privacy disclosures and controls."""
import argparse
import difflib
from pathlib import Path
import re
import subprocess
import merlin_mark
from generate_design_tokens import DATA

ROOT=Path(__file__).resolve().parent.parent
# Eye contour, reverse inner contour, pupil, then privacy slash. Nonzero fill.
COMMANDS=[('MOVE_TO',[2,12]),('CUBIC_TO',[4,8,7.5,5,12,5]),('CUBIC_TO',[16.5,5,20,8,22,12]),('CUBIC_TO',[20,16,16.5,19,12,19]),('CUBIC_TO',[7.5,19,4,16,2,12]),('CLOSE',[]),('MOVE_TO',[4.5,12]),('CUBIC_TO',[6.5,15.5,9,17,12,17]),('CUBIC_TO',[15,17,17.5,15.5,19.5,12]),('CUBIC_TO',[17.5,8.5,15,7,12,7]),('CUBIC_TO',[9,7,6.5,8.5,4.5,12]),('CLOSE',[]),('CIRCLE',[12,12,3]),('MOVE_TO',[3,2]),('LINE_TO',[22,21]),('LINE_TO',[20.5,22.5]),('LINE_TO',[1.5,3.5]),('CLOSE',[])]


def svg(splash):
    eye='M2 12C4 8 7.5 5 12 5S20 8 22 12C20 16 16.5 19 12 19S4 16 2 12Z M4.5 12C6.5 15.5 9 17 12 17S17.5 15.5 19.5 12C17.5 8.5 15 7 12 7S6.5 8.5 4.5 12Z M3 2L22 21 20.5 22.5 1.5 3.5Z'
    if not splash:return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><rect width="24" height="24" rx="6" fill="{merlin_mark.CREAM}"/><path fill="{merlin_mark.FOREST}" d="{eye}"/><circle cx="12" cy="12" r="3" fill="{merlin_mark.FOREST}"/></svg>\n'
    return f'''<!-- Generated by scripts/generate_private_identity.py. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" width="120" height="120">
  <rect x="4" y="4" width="104" height="104" rx="28" fill="{merlin_mark.CREAM}"/>
  <path d="{merlin_mark.glyph_path(20,13,72)}" fill="{merlin_mark.FOREST}"/>
  <g transform="translate(77 77) scale(1.5)">
    <circle cx="12" cy="12" r="14" fill="{DATA['native']['light']['accent']}"/>
    <path d="{eye}" fill="{DATA['native']['light']['on_surface']}"/><circle cx="12" cy="12" r="3" fill="{DATA['native']['light']['on_surface']}"/>
  </g>
</svg>
'''


def vector(original):
    result='// Copyright 2026 The Merlin Authors\n// Use of this source code is governed by a BSD-style license that can be\n// found in the LICENSE file.\n//\n// Merlin private mode: eye with privacy slash. Generated by scripts/generate_private_identity.py.\n'
    for dimension in re.findall(r'CANVAS_DIMENSIONS, (\d+),',original):
        scale=int(dimension)/24
        result+=f'CANVAS_DIMENSIONS, {dimension},\nFILL_RULE_NONZERO,\n'
        for command,values in COMMANDS:
            result+=command+(', '+', '.join(f'{value*scale:.4f}f' for value in values) if values else '')+',\n'
    return result


def resources(src):
    for name in ('incognito_icon','incognito_splash'):
        yield f'ui/webui/resources/images/{name}.svg',lambda original,n=name:svg(n.endswith('splash'))
    for name in ('incognito','incognito_old','incognito_circle_filled','incognito_refresh_menu_old'):
        yield f'chrome/app/vector_icons/{name}.icon',vector


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--src',type=Path,default=Path.home()/'chromium/src');p.add_argument('--check',action='store_true');a=p.parse_args();patch=[]
    for path,convert in resources(a.src):
        before=subprocess.check_output(['git','-C',str(a.src),'show','HEAD:'+path],text=True);after=convert(before)
        if a.check:
            if (a.src/path).read_text()!=after:raise SystemExit('stock private artwork: '+path)
        else:
            for line in difflib.unified_diff(before.splitlines(True),after.splitlines(True),fromfile='a/'+path,tofile='b/'+path):
                patch.append(line if line.endswith('\n') else line+'\n\\ No newline at end of file\n')
    if not a.check:(ROOT/'patches/0036-merlin-private-identity.patch').write_text(''.join(patch))
    print('private identity: '+('verified' if a.check else 'generated'))

if __name__=='__main__':main()
