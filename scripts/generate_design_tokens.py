#!/usr/bin/env python3
"""Generate native/WebUI tokens from Settings' palette. --check fails on drift."""
import argparse
import json
import re
from urllib.parse import quote
import merlin_mark
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / 'branding/design_tokens.json').read_text())
HEADER = ROOT / 'overlay/chrome/browser/ui/modal_browser/merlin_design_tokens.h'
CSS = ROOT / 'branding/generated/merlin_webui_tokens.css'


def declarations(values):
    return ''.join(f'  --{key}: {value};\n' for key, value in values.items())


def generate():
    metrics = DATA['metrics']
    web_modes = {mode: {key: (DATA['native'][mode][value[1:]] if value.startswith('$') else value) for key,value in values.items()} for mode,values in DATA['web'].items()}
    common = {'font': DATA['font'], **{k.replace('_', '-'): f'{v}px' for k, v in metrics.items()}}
    page = ':root {\n  color-scheme: light dark;\n' + declarations({**web_modes['light'], **common}) + '}\n'
    page += '@media (prefers-color-scheme: dark) {\n:root {\n' + declarations(web_modes['dark']) + '}\n}\n'
    # Only decorative/neutral tokens; Chromium owns warning and error semantics.
    aliases = {
        'cr-primary-text-color': 'text', 'cr-secondary-text-color': 'text2',
        'cr-card-background-color': 'panel', 'cr-dialog-background-color': 'panel',
        'cr-toolbar-background-color': 'bg', 'cr-card-border-radius': 'card-radius',
        'cr-dialog-border-radius': 'dialog-radius', 'cr-button-border-radius': 'control-radius',
        'cr-separator-color': 'hair', 'cr-focus-outline-color': 'focus',
        'cr-form-field-label-color': 'text2', 'cr-input-background-color': 'sunk',
        'cr-hover-background-color': 'hover', 'cr-active-background-color': 'select',
        'cr-link-color': 'link', 'cr-checked-color': 'link',
        'cr-button-text-color': 'text', 'cr-button-background-color': 'kbd',
        'cr-button-border-color': 'hair', 'cr-button-ripple-color': 'hover',
        'cr-button-height': 'control-height',
    }
    # The accent fill and link color have different contrast requirements.
    page = page.replace('--font:', '--control-height: 30px;\n  --font:')
    web = '/* Generated by scripts/generate_design_tokens.py. */\n'
    extra = declarations({k:f'var(--{v})' for k,v in aliases.items()})
    extra += '  --cr-card-shadow: var(--shadow);\n  --cr-title-text-font-family: var(--font);\n  --cr-button-edge-space: 12px;\n'
    web_page = page.replace('}\n', extra + '}\n', 1).replace(':root', 'html')
    web += '@media (forced-colors: none) and (prefers-contrast: no-preference) {\n' + web_page
    web += 'body {\n  font-family: var(--font);\n  background-color: var(--bg);\n  color: var(--text);\n}\n}\n'
    web = web.replace('"', "'")
    web = re.sub(r'#([0-9a-fA-F])\1([0-9a-fA-F])\2([0-9a-fA-F])\3\b', r'#\1\2\3', web)
    header = '// Generated by scripts/generate_design_tokens.py. Do not edit.\n'
    header += '#ifndef CHROME_BROWSER_UI_MODAL_BROWSER_MERLIN_DESIGN_TOKENS_H_\n#define CHROME_BROWSER_UI_MODAL_BROWSER_MERLIN_DESIGN_TOKENS_H_\n\n#include "third_party/skia/include/core/SkColor.h"\n\nnamespace modal_browser::design {\n'
    header += 'struct Palette {\n' + ''.join(f'  SkColor {key};\n' for key in DATA['native']['light']) + '};\n'
    for mode in ('light','dark'):
        header += f'inline constexpr Palette k{mode.title()} = {{\n'
        header += ''.join(f'    .{key} = 0xFF{value[1:]},\n' for key,value in DATA['native'][mode].items()) + '};\n'
    header += 'struct OverlayPalette {\n' + ''.join(f'  SkColor {key};\n' for key in DATA['overlay']['light']) + '};\n'
    for mode in ('light', 'dark'):
        header += f'inline constexpr OverlayPalette k{mode.title()}Overlay = {{\n'
        header += ''.join(f'    .{key} = 0x{value[1:] if len(value)==9 else "FF"+value[1:]},\n' for key,value in DATA['overlay'][mode].items()) + '};\n'
    header += ''.join(f'inline constexpr int k{"".join(x.title() for x in key.split("_"))} = {value};\n' for key,value in metrics.items())
    start_css = ':root {\n' + declarations(DATA['start']['light']) + '}\n'
    start_css += '@media (prefers-color-scheme: dark) {\n:root {\n' + declarations(DATA['start']['dark']) + '}\n}\n'
    product_svg = merlin_mark.tile_svg()
    header += f'inline constexpr char kProductIconSvg[] = R"SVG({product_svg})SVG";\n'
    header += f'inline constexpr char kProductIconCssUrl[] = R"URL(url("data:image/svg+xml,{quote(product_svg, safe="")}"))URL";\n'
    header += f'inline constexpr char kStartTokensCss[] = R"CSS({start_css})CSS";\n'
    header += f'inline constexpr char kPageTokensCss[] = R"CSS({page})CSS";\n'
    header += '}  // namespace modal_browser::design\n\n#endif  // CHROME_BROWSER_UI_MODAL_BROWSER_MERLIN_DESIGN_TOKENS_H_\n'
    # Components without a native color provider use Chromium's fallback roles.
    # Keep semantic error/warning/disabled roles under Chromium's control.
    fallback = {
        'primary': 'link', 'on-primary': 'panel', 'primary-container': 'select',
        'on-primary-container': 'text', 'secondary-container': 'select',
        'on-secondary-container': 'text', 'neutral-container': 'sunk',
        'neutral-outline': 'hair', 'outline': 'text3', 'surface': 'panel',
        **{f'surface{i}': 'sunk' for i in range(1, 6)},
        'surface-variant': 'sunk', 'on-surface': 'text',
        'on-surface-variant': 'text2', 'on-surface-subtle': 'text2',
        'tonal-container': 'select', 'on-tonal-container': 'text',
        'tonal-outline': 'hair', 'divider': 'hair', 'base-container': 'bg',
    }
    component = '/* Generated by scripts/generate_design_tokens.py. */\n'
    component += '@media (forced-colors: none) and (prefers-contrast: no-preference) {\nhtml {\n'
    component += declarations({'cr-fallback-color-' + k: f'var(--{v})' for k,v in fallback.items()})
    component += '}\n}\n'
    return {HEADER:header, CSS:web, ROOT / 'branding/generated/merlin_page_tokens.css': page,
            ROOT / 'branding/generated/merlin_component_tokens.css': component}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    stale=[]
    for path,content in generate().items():
        if args.check:
            if not path.exists() or path.read_text()!=content: stale.append(str(path.relative_to(ROOT)))
        else: path.write_text(content)
    if stale: raise SystemExit('stale generated tokens: '+', '.join(stale))
    print('design tokens: current' if args.check else 'design tokens: generated')

if __name__=='__main__': main()
