#!/usr/bin/env python3
"""Keep the shell/Chromium contract defined once. No build required.

- The C ABI declarations are byte-identical in packages/engine/include and
  the overlay.
- The shell vocabulary (packages/engine/include/merlin_shell_vocabulary.json:
  every bridge method and the enum values its arguments take) generates
  packages/engine/src/vocabulary.ts and the overlay's
  merlin_shell_vocabulary.h.
- Native shell code never spells a method name itself, and every vocabulary
  constant it uses exists, so renaming a name in one place fails the check.

`--check` reports drift; without it the copies are rewritten.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INCLUDE = ROOT / 'packages/engine/include'
OVERLAY = ROOT / 'overlay/chrome/browser/ui/modal_browser'
VOCABULARY = INCLUDE / 'merlin_shell_vocabulary.json'
TS_OUT = ROOT / 'packages/engine/src/vocabulary.ts'
CC_OUT = OVERLAY / 'merlin_shell_vocabulary.h'
ABI_PAIRS = {
    'MerlinEngineAPI.h': 'merlin_shell_api.h',
    'MerlinShellAPI.h': 'merlin_shell_host_api.h',
}
NOTICE = ('Generated by scripts/sync_shell_headers.py from packages/engine/include/merlin_shell_vocabulary.json.'
          ' Do not edit.')
METHOD_GROUPS = {'calls': 'call', 'requests': 'request', 'nativeOnly': 'nativeOnly'}


def words(name):
    """'modal.palette.text', 'hint_chars', 'ctrlTab' -> ['modal', 'palette', 'text'] and so on."""
    return [w for w in re.split(r'[._\-]|(?<=[a-z0-9])(?=[A-Z])', name) if w]


def constant(name):
    return 'k' + ''.join(w[0].upper() + w[1:] for w in words(name))


def snake(name):
    return '_'.join(w.lower() for w in words(name))


def pascal(name):
    return ''.join(w[0].upper() + w[1:] for w in words(name))


def plural(name):
    """The TypeScript list's name: downloadActions, securities."""
    return name[:-1] + 'ies' if name.endswith('y') and name[-2:-1] not in 'aeiou' else name + 's'


def load():
    data = json.loads(VOCABULARY.read_text())
    problems = []
    if set(data['methods']) != set(METHOD_GROUPS):
        problems.append(f'methods must have exactly {sorted(METHOD_GROUPS)}')
    names = [m for group in data['methods'].values() for m in group]
    for value in names:
        if not re.fullmatch(r'[a-z]+(\.[a-z][a-zA-Z]*)+', value):
            problems.append(f'method {value!r} is not dotted camelCase')
    if len(names) != len(set(names)):
        problems.append('a method is listed twice')
    if len({constant(m) for m in names}) != len(names):
        problems.append('two methods map to the same C++ constant')
    for enum, values in data['enums'].items():
        if not re.fullmatch(r'[a-z][a-zA-Z]*', enum):
            problems.append(f'enum {enum!r} is not camelCase')
        if not values or len(values) != len(set(values)) or len({constant(v) for v in values}) != len(values):
            problems.append(f'enum {enum!r} is empty, repeats a value or has values with the same C++ constant')
        for value in values:
            if not re.fullmatch(r'[a-z][a-zA-Z0-9_]*', value):
                problems.append(f'{enum} value {value!r} is not an identifier')
    if problems:
        sys.exit('merlin_shell_vocabulary.json: ' + '; '.join(problems))
    return data


def typescript(data):
    def array(name, values):
        inline = f"export const {name} = [{', '.join(repr(v) for v in values)}] as const;"
        if len(inline) <= 120:
            return [inline]
        return [f'export const {name} = [', *(f"  {v!r}," for v in values), '] as const;']
    out = [f'// {NOTICE}', '']
    for group, kind in METHOD_GROUPS.items():
        out += array(f'{kind}Methods', data['methods'][group])
        out.append(f'export type {pascal(kind)}Method = typeof {kind}Methods[number];')
    for enum, values in data['enums'].items():
        out += array(plural(enum), values)
        out.append(f'export type {pascal(enum)} = typeof {plural(enum)}[number];')
    return '\n'.join(out) + '\n'


def cpp(data):
    guard = 'CHROME_BROWSER_UI_MODAL_BROWSER_MERLIN_SHELL_VOCABULARY_H_'
    out = [f'// {NOTICE}', '//', '// The shell bridge\'s method names and argument values. Compare against these,',
           '// never against a string literal, so the TypeScript protocol and native code',
           '// cannot drift apart (scripts/sync_shell_headers.py --check).', '',
           f'#ifndef {guard}', f'#define {guard}', '', '#include <array>', '#include <string_view>', '',
           'namespace modal_browser::shell {', '', 'namespace method {']
    for group in METHOD_GROUPS:
        out.append(f'// {group}')
        out += [f'inline constexpr char {constant(m)}[] = "{m}";' for m in data['methods'][group]]
    for group in METHOD_GROUPS:
        methods = data['methods'][group]
        out.append(f'inline constexpr std::array<std::string_view, {len(methods)}> {constant(group)} = {{')
        out += [f'    {constant(m)},' for m in methods]
        out.append('};')
    out += ['}  // namespace method', '']
    for enum, values in data['enums'].items():
        out.append(f'namespace {snake(enum)} {{')
        out += [f'inline constexpr char {constant(v)}[] = "{v}";' for v in values]
        members = ', '.join(constant(v) for v in values)
        out.append(f'inline constexpr std::array<std::string_view, {len(values)}> kAll = {{{members}}};')
        out += [f'}}  // namespace {snake(enum)}', '']
    out += ['}  // namespace modal_browser::shell', '', f'#endif  // {guard}']
    return '\n'.join(out) + '\n'


def native_problems(data):
    """Method names spelled out in native shell code, and constants it uses that don't exist."""
    methods = {m for group in data['methods'].values() for m in group}
    defined = {'method': {constant(m) for m in methods} | {constant(group) for group in METHOD_GROUPS}}
    defined.update({snake(enum): {constant(v) for v in values} | {'kAll'} for enum, values in data['enums'].items()})
    problems = []
    for path in sorted(OVERLAY.glob('*')):
        if path.suffix not in ('.cc', '.mm', '.h') or path == CC_OUT:
            continue
        for number, line in enumerate(path.read_text().splitlines(), 1):
            where = f'{path.relative_to(ROOT)}:{number}'
            for literal in re.findall(r'"([a-z]+(?:\.[a-zA-Z]+)+)"', line):
                if literal in methods:
                    problems.append(f'{where} spells "{literal}"; use shell::method::{constant(literal)}')
            for space, name in re.findall(r'\bshell::([a-z_]+)::(k[A-Za-z0-9]+)\b', line):
                if name not in defined.get(space, ()):
                    problems.append(f'{where} uses shell::{space}::{name}, which the vocabulary does not define')
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = load()
    wanted = {INCLUDE / source: (OVERLAY / target, None) for source, target in ABI_PAIRS.items()}
    generated = {TS_OUT: typescript(data).encode(), CC_OUT: cpp(data).encode()}
    if args.check:
        stale = [target.name for source, (target, _) in wanted.items()
                 if not target.exists() or target.read_bytes() != source.read_bytes()]
        stale += [path.name for path, content in generated.items()
                  if not path.exists() or path.read_bytes() != content]
        problems = [f'{name} is out of date; run scripts/sync_shell_headers.py' for name in stale]
        problems += native_problems(data)
        if problems:
            sys.exit('\n'.join(problems))
        print('Shell ABI headers and vocabulary match')
        return
    for source, (target, _) in wanted.items():
        target.write_bytes(source.read_bytes())
    for path, content in generated.items():
        path.write_bytes(content)
    problems = native_problems(data)
    print('Shell ABI headers and vocabulary synchronized')
    if problems:
        sys.exit('\n'.join(problems))


if __name__ == '__main__':
    main()
