#!/usr/bin/env python3
"""Catalog browser-owned presentation sources and inherited-style review leads.

Source inspection is not runtime qualification. No files in Chromium are edited.
"""
import argparse
import csv
from pathlib import Path
import re
import rebrand_remaining_names

ROOT=Path(__file__).resolve().parent.parent
ROOTS=('ui/views/controls','ui/views/bubble','ui/views/window','ui/views/layout','ui/color',
       'content/browser/resources','third_party/devtools-frontend/src/front_end','chrome/browser/ui/modal_browser','chrome/browser/ui/views','chrome/browser/ui/cocoa','chrome/browser/resources',
       'ui/webui/resources/cr_elements','ui/webui/resources/cr_components',
       'components/global_media_controls','components/media_message_center',
       'components/security_interstitials','components/neterror',
       'components/javascript_dialogs','components/permissions',
       'components/web_modal','components/webui','chrome/app',
       'chrome/browser/ui/webauthn','chrome/browser/ui/autofill',
       'chrome/app/vector_icons','components/vector_icons','ui/webui/resources/images')
BITMAPS={'.png','.webp','.avif','.gif','.jpg','.jpeg'}
SUFFIXES={'.cc','.h','.mm','.html','.css','.ts','.js','.grd','.grdp','.svg','.icon','.json',*BITMAPS}
SKIP=re.compile(r'(^|/)(?:tests?|testing|test_support)(?:/|_)|(?:_test|_tests|_unittest|_browsertest|_uitest|_interactive_uitest)\.|\.test\.|(?:^|/)(?:mock|fake)_|/(?:android|chromeos|ash|ios)/')


def category(path):
    groups=(('password','1-passwords'),('webauthn','1-passkeys'),('media','1-media'),
            ('permission','2-permissions'),('page_info','2-site-info'),
            ('certificate','2-certificates'),('security_interstitial','2-warnings'),
            ('neterror','2-network-errors'),('chooser','2-device-choosers'),
            ('autofill','3-autofill'),('payment','3-payments'),
            ('profile','4-profiles'),('signin','4-profiles'),('extension','4-extensions'),
            ('side_panel','4-side-panels'),('bookmark','4-library'),('history','4-library'),
            ('setting','5-settings'),('download','5-downloads'),('print','5-printing'),
            ('incognito','5-private'),('guest','5-private'),('ntp','5-start'),
            ('session','6-recovery'),('crash','6-recovery'),('startup','6-recovery'),
            ('javascript','6-dialogs'),('login','6-auth'),('toolbar','6-toolbar'),
            ('menu','6-menus'),('frame','6-window'),('tab','6-tabs'))
    for key,value in groups:
        if key in path: return value
    return '6-other-and-shared'


def inventory(src):
    seen=set()
    for base in (*ROOTS, *rebrand_remaining_names.FILES):
        directory=src/base
        if not directory.exists(): continue
        for path in sorted(directory.rglob('*')) if directory.is_dir() else [directory]:
            rel=path.relative_to(src).as_posix()
            if not path.is_file() or path.suffix not in SUFFIXES or SKIP.search(rel) or rel in seen: continue
            seen.add(rel)
            binary=path.suffix in BITMAPS
            text='' if binary else path.read_text(errors='replace')
            # Animation JSON is presentation. Locale/build/config JSON is not
            # an independent surface and would obscure the actionable catalog.
            if path.suffix == '.json' and not (
                    '"layers"' in text and '"fr"' in text and '"v"' in text):
                continue
            colors=sorted(set(re.findall(r'#[0-9a-fA-F]{3,8}\b|SkColorSet(?:RGB|ARGB)\([^\n]*?\)',text)))
            artwork=sorted(set(re.findall(r'IDR_[A-Z0-9_]*(?:LOGO|PROMO|ILLUSTRATION|LOTTIE|BANNER|CHROME)[A-Z0-9_]*|[\w/.-]*(?:logo|promo|illustration|banner)[\w/.-]*\.(?:svg|png|webp)',text)))
            signals=['native-image-review'] if binary else []
            if path.suffix == '.json': signals.append('lottie-artwork-review')
            if path.suffix in {'.svg','.icon'}: signals.append('vector-artwork-review')
            if 'Generated by scripts/generate_identity_artwork.py' in text: signals.append('merlin-artwork')
            if colors: signals.append('literal-colors:'+str(len(colors)))
            if re.search(r'font-family|FontList|Typography',text): signals.append('typography')
            if re.search(r'border-radius|CornerRadius|RoundedCorners',text): signals.append('corners')
            if re.search(r'kColor|--cr-|--color-|--sys-',text): signals.append('shared-color-tokens')
            visible_source=re.sub(r'/\*.*?\*/|<!--.*?-->|^[ \t]*//[^\n]*', '', text, flags=re.S|re.M)
            if re.search(r'\b(?:Chrome|Chromium)\b',visible_source): signals.append('product-name-review')
            yield {'batch':category(rel),'source':rel,'inherited_style_signals':','.join(signals),
                   'artwork_review_leads':','.join(artwork),'runtime_status':'not-qualified'}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--src',type=Path,default=Path.home()/'chromium/src');p.add_argument('--output',type=Path,default=ROOT/'docs/visual-identity-sources.tsv');a=p.parse_args()
    rows=sorted(inventory(a.src),key=lambda r:(r['batch'],r['source']))
    with a.output.open('w') as f:
        writer=csv.DictWriter(f,fieldnames=rows[0].keys(),delimiter='\t');writer.writeheader();writer.writerows(rows)
    print(f'{len(rows)} presentation source files cataloged in {a.output}')

if __name__=='__main__': main()
