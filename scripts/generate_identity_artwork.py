#!/usr/bin/env python3
"""Replace explicitly inventoried promotional SVGs with Merlin vector artwork.

Keeps original resource names and dimensions. Checkup states retain distinct
safe/running/error/compromised symbols and colors. Never changes website media,
provider/payment marks, authenticator QR codes or security-interstitial artwork.
"""
import argparse
import difflib
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET
import merlin_mark
from generate_design_tokens import DATA

ROOT=Path(__file__).resolve().parent.parent
MANIFEST=json.loads((ROOT/'branding/identity_artwork.json').read_text())


def artwork(original,role,dark):
    element=ET.fromstring(original)
    box=element.get('viewBox')
    if not box:
        box='0 0 '+element.get('width','316').removesuffix('px')+' '+element.get('height','112').removesuffix('px')
    x,y,w,h=map(float,box.split())
    mode='dark' if dark else 'light'
    paper=DATA['native'][mode]['base_container'] if dark else DATA['web'][mode]['sunk']
    ink=DATA['native'][mode]['on_surface']
    muted=DATA['native'][mode]['on_surface_subtle']
    status={'safe':DATA['web'][mode]['ok'],'error':DATA['web'][mode]['danger'],'compromised':DATA['web'][mode]['danger']}.get(role,ink)
    shapes={
      'key':'<circle cx="59" cy="45" r="9"/><path d="M66 51l17 17m-7-7l5-5m-11-1l5-5"/>',
      'profiles':'<circle cx="66" cy="39" r="8"/><path d="M49 65v-5a17 17 0 0 1 34 0v5"/>',
      'devices':'<rect x="46" y="31" width="35" height="26" rx="3"/><path d="M43 63h41"/><rect x="77" y="42" width="14" height="24" rx="3"/>',
      'bookmarks':'<path d="M56 31h25v36L68.5 59 56 67z"/>',
      'shield':'<path d="M68 27l19 8v16c0 13-19 22-19 22s-19-9-19-22V35z"/>',
      'safe':'<path d="M68 27l19 8v16c0 13-19 22-19 22s-19-9-19-22V35zM58 49l7 7 14-15"/>',
      'compromised':'<path d="M68 27l19 8v16c0 13-19 22-19 22s-19-9-19-22V35zM68 39v14m0 8v1"/>',
      'error':'<circle cx="68" cy="50" r="21"/><path d="M61 43l14 14m0-14L61 57"/>',
      'running':'<circle cx="68" cy="50" r="21" stroke-dasharray="4 5"/><path d="M68 36v15l9 6"/>',
    }
    scale=min(w/160,h/100)
    return f'''<!-- Generated by scripts/generate_identity_artwork.py: {role}. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}" width="{w:g}" height="{h:g}" fill="none">
  <g transform="translate({x+(w-160*scale)/2:g} {y+(h-100*scale)/2:g}) scale({scale:g})">
    <rect x="28" y="17" width="104" height="66" rx="14" fill="{paper}"/>
    <path d="M100 32h16m-16 9h10m-10 9h16m-16 9h10" stroke="{muted}" stroke-opacity=".35" stroke-width="2" stroke-linecap="round"/>
    <g stroke="{status}" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round">{shapes[role]}</g>
    <rect x="17" y="60" width="28" height="28" rx="8" fill="{merlin_mark.CREAM}"/>
    <path d="{merlin_mark.glyph_path(19,62,24)}" fill="{merlin_mark.FOREST}"/>
  </g>
</svg>
'''


def resources(src):
    for directory,roles in MANIFEST.items():
        found=set()
        for path in sorted((src/directory).glob('*.svg')):
            stem=path.stem
            role=roles.get(stem) or roles.get(re.sub(r'_dark$','',stem))
            if role:
                found.add(stem if stem in roles else re.sub(r'_dark$','',stem))
                yield path.relative_to(src).as_posix(),role,'dark' in stem
        missing=set(roles)-found
        if missing:raise ValueError(f'missing artwork in {directory}: {missing}')


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--src',type=Path,default=Path.home()/'chromium/src');p.add_argument('--check',action='store_true');a=p.parse_args()
    patch=[];count=0
    for path,role,dark in resources(a.src):
        original=subprocess.check_output(['git','-C',str(a.src),'show','HEAD:'+path],text=True)
        replacement=artwork(original,role,dark);count+=1
        if a.check:
            if (a.src/path).read_text()!=replacement:raise SystemExit('unexpected artwork: '+path)
            continue
        for line in difflib.unified_diff(original.splitlines(True),replacement.splitlines(True),fromfile='a/'+path,tofile='b/'+path):
            patch.append(line if line.endswith('\n') else line+'\n\\ No newline at end of file\n')
    if not a.check:(ROOT/'patches/0034-merlin-presentation-artwork.patch').write_text(''.join(patch))
    print(f'{count} Merlin artwork resources '+('verified' if a.check else 'generated'))

if __name__=='__main__':main()
